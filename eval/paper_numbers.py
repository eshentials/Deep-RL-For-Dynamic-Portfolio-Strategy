def num(x, nd=3, sign=False, pct=False):
    """A number for LaTeX math mode, with a true minus sign."""
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return ""
    v = float(x) * (100 if pct else 1)
    s = f"{abs(v):,.{nd}f}".replace(",", "{,}")
    s = ("-" if v < 0 else ("+" if sign else "")) + s
    return f"${s}{'\\%' if pct else ''}$"


def short_period(p):
    return {"2019-2026 (all)": "2019--2026", "2019-2021 (not previously seen)": "2019--2021 (unseen)",
            "2022-2026 (previously seen)": "2022--2026 (seen)", "All years except 2020": "All but 2020"}.get(p, p)


def ci(lo, hi, nd=3):
    return f"[{num(lo, nd, True)}, {num(hi, nd, True)}]"


class Macros:
    def __init__(self):
        self.lines = ["% Generated by `python -m eval.paper_numbers` from the committed results. Do not edit."]

    def __setitem__(self, name, value):
        assert name.isalpha(), name
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def table(path, cols, rows, align=None, notes=None):
    align = align or "l" + "r" * (len(cols) - 1)
    L = [f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(cols) + " \\\\", "\\midrule"]
    for r in rows:
        L.append("\\midrule" if r == "MID" else " & ".join(r) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    (OUT / path).write_text("\n".join(L) + "\n")


